// The reference plug-in's bundled MSVC CRT uses this thread-local rand()
// recurrence. New per-thread data starts at 1; the plug-in's one-time parent
// initialization can replace that state with a time-derived seed.
inline std::uint32_t& binaryMsvcRandState() {
    static thread_local std::uint32_t holdrand = 1;
    return holdrand;
}

inline void binaryMsvcSrand(std::uint32_t seed) {
    binaryMsvcRandState() = seed;
}

inline std::int32_t binaryMsvcRand15() {
    std::uint32_t& holdrand = binaryMsvcRandState();
    holdrand = holdrand * 0x343fdu + 0x269ec3u;
    return static_cast<std::int32_t>((holdrand >> 16) & 0x7fffu);
}

